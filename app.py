@app.route("/tickets/stats")
def ticket_stats():
    """Return aggregate ticket counts by status, priority, and category."""
    ensure_tables()
    total_rows = lakebase.run_query(f"SELECT COUNT(*) AS total FROM {TICKETS_TABLE}")
    total = int(total_rows[0]["total"]) if total_rows else 0

    def _counts(column: str, allowed: tuple[str, ...]) -> dict[str, int]:
        rows = lakebase.run_query(
            f"""
            SELECT {column} AS key, COUNT(*) AS count
            FROM {TICKETS_TABLE}
            GROUP BY {column}
            """
        )
        counts = {name: 0 for name in allowed}
        for row in rows:
            key = row.get("key")
            if key in counts:
                counts[key] = int(row["count"])
            elif key is not None:
                counts[str(key)] = int(row["count"])
        return counts

    return jsonify(
        {
            "total": total,
            "by_status": _counts("status", VALID_STATUSES),
            "by_priority": _counts("priority", VALID_PRIORITIES),
            "by_category": _counts("category", VALID_CATEGORIES),
        }
    )


@app.route("/tickets", methods=["GET"])
def list_tickets():
    """Return support tickets, optionally filtered by status, newest first."""
    ensure_tables()

    status = request.args.get("status")
    priority = request.args.get("priority")
    category = request.args.get("category")
    fields: dict[str, str] = {}

    if status not in (None, "", "all"):
        cleaned, err = _validate_choice(
            status, field="status", allowed=VALID_STATUSES, required=True
        )
        if err:
            fields["status"] = err
        status = cleaned
    else:
        status = None

    if priority not in (None, "", "all"):
        cleaned, err = _validate_choice(
            priority, field="priority", allowed=VALID_PRIORITIES, required=True
        )
        if err:
            fields["priority"] = err
        priority = cleaned
    else:
        priority = None

    if category not in (None, "", "all"):
        cleaned, err = _validate_choice(
            category, field="category", allowed=VALID_CATEGORIES, required=True
        )
        if err:
            fields["category"] = err
        category = cleaned
    else:
        category = None

    if fields:
        return _error("Invalid filter parameters.", fields=fields)

    clauses = []
    params: list = []
    if status:
        clauses.append("status = %s")
        params.append(status)
    if priority:
        clauses.append("priority = %s")
        params.append(priority)
    if category:
        clauses.append("category = %s")
        params.append(category)

    where = f"WHERE {' AND '.join(clauses)}" if clauses else ""
    rows = lakebase.run_query(
        f"""
        SELECT {TICKET_COLUMNS}
        FROM {TICKETS_TABLE}
        {where}
        ORDER BY created_at DESC
        """,
        tuple(params) if params else None,
    )
    return jsonify([_serialize_row(r) for r in rows])


@app.route("/tickets", methods=["POST"])
def create_ticket():
    """Create a new support ticket."""
    ensure_tables()

    data = request.get_json(silent=True)
    if data is None:
        return _error("Request body must be JSON with ticket fields.")

    fields: dict[str, str] = {}
    title, err = _validate_title(data.get("title"))
    if err:
        fields["title"] = err

    status, err = _validate_choice(
        data.get("status"),
        field="status",
        allowed=VALID_STATUSES,
        default="open",
    )
    if err:
        fields["status"] = err

    priority, err = _validate_choice(
        data.get("priority"),
        field="priority",
        allowed=VALID_PRIORITIES,
        default="medium",
    )
    if err:
        fields["priority"] = err

    category, err = _validate_choice(
        data.get("category"),
        field="category",
        allowed=VALID_CATEGORIES,
        default="general",
    )
    if err:
        fields["category"] = err

    if fields:
        return _error("Please fix the highlighted fields and try again.", fields=fields)

    created_by = _current_user_email()
    rows = lakebase.run_write_returning(
        f"""
        INSERT INTO {TICKETS_TABLE}
            (title, status, priority, category, created_by, created_at)
        VALUES (%s, %s, %s, %s, %s, now())
        RETURNING {TICKET_COLUMNS}
        """,
        (title, status, priority, category, created_by),
    )
    return jsonify(_serialize_row(rows[0])), 201


@app.route("/tickets/<ticket_id>", methods=["GET"])
def get_ticket(ticket_id: str):
    """Return a single ticket by id."""
    ensure_tables()
    parsed_id = _parse_ticket_id(ticket_id)
    if parsed_id is None:
        return _error(
            "Invalid ticket id. Use a numeric ticket_id from the tickets list."
        )

    ticket = _get_ticket_or_none(parsed_id)
    if not ticket:
        return _error(f"Ticket #{parsed_id} was not found.", 404)
    return jsonify(_serialize_row(ticket))


@app.route("/tickets/<ticket_id>", methods=["DELETE"])
def delete_ticket(ticket_id: str):
    """Delete a ticket and all of its messages."""
    ensure_tables()
    parsed_id = _parse_ticket_id(ticket_id)
    if parsed_id is None:
        return _error(
            "Invalid ticket id. Use a numeric ticket_id from the tickets list."
        )

    ticket = _get_ticket_or_none(parsed_id)
    if not ticket:
        return _error(f"Ticket #{parsed_id} was not found.", 404)

    lakebase.run_write(
        f"DELETE FROM {MESSAGES_TABLE} WHERE ticket_id = %s",
        (parsed_id,),
    )
    deleted = lakebase.run_write(
        f"DELETE FROM {TICKETS_TABLE} WHERE ticket_id = %s",
        (parsed_id,),
    )
    if deleted == 0:
        return _error(f"Ticket #{parsed_id} was not found.", 404)

    return jsonify(
        {
            "deleted": True,
            "ticket_id": parsed_id,
            "title": ticket.get("title"),
        }
    )


@app.route("/tickets/<ticket_id>/status", methods=["PATCH", "PUT"])
def update_ticket_status(ticket_id: str):
    """Update a ticket's status."""
    ensure_tables()
    parsed_id = _parse_ticket_id(ticket_id)
    if parsed_id is None:
        return _error(
            "Invalid ticket id. Use a numeric ticket_id from the tickets list."
        )

    data = request.get_json(silent=True)
    if data is None:
        return _error('Request body must be JSON, e.g. {"status": "solved"}.')

    status, err = _validate_choice(
        data.get("status"),
        field="status",
        allowed=VALID_STATUSES,
        required=True,
    )
    if err:
        return _error(err, fields={"status": err})

    updated = lakebase.run_write(
        f"""
        UPDATE {TICKETS_TABLE}
        SET status = %s
        WHERE ticket_id = %s
        """,
        (status, parsed_id),
    )
    if updated == 0:
        return _error(f"Ticket #{parsed_id} was not found.", 404)

    ticket = _get_ticket_or_none(parsed_id)
    return jsonify(_serialize_row(ticket))


@app.route("/tickets/<ticket_id>", methods=["PATCH"])
def update_ticket(ticket_id: str):
    """Update ticket fields (status, priority, and/or category)."""
    ensure_tables()
    parsed_id = _parse_ticket_id(ticket_id)
    if parsed_id is None:
        return _error(
            "Invalid ticket id. Use a numeric ticket_id from the tickets list."
        )

    data = request.get_json(silent=True)
    if data is None:
        return _error("Request body must be JSON with fields to update.")

    if not _get_ticket_or_none(parsed_id):
        return _error(f"Ticket #{parsed_id} was not found.", 404)

    fields: dict[str, str] = {}
    updates: list[str] = []
    params: list = []

    if "status" in data:
        status, err = _validate_choice(
            data.get("status"),
            field="status",
            allowed=VALID_STATUSES,
            required=True,
        )
        if err:
            fields["status"] = err
        else:
            updates.append("status = %s")
            params.append(status)

    if "priority" in data:
        priority, err = _validate_choice(
            data.get("priority"),
            field="priority",
            allowed=VALID_PRIORITIES,
            required=True,
        )
        if err:
            fields["priority"] = err
        else:
            updates.append("priority = %s")
            params.append(priority)

    if "category" in data:
        category, err = _validate_choice(
            data.get("category"),
            field="category",
            allowed=VALID_CATEGORIES,
            required=True,
        )
        if err:
            fields["category"] = err
        else:
            updates.append("category = %s")
            params.append(category)

    if fields:
        return _error("Please fix the highlighted fields and try again.", fields=fields)
    if not updates:
        return _error(
            "No updatable fields provided. Send status, priority, and/or category."
        )

    params.append(parsed_id)
    lakebase.run_write(
        f"""
        UPDATE {TICKETS_TABLE}
        SET {', '.join(updates)}
        WHERE ticket_id = %s
        """,
        tuple(params),
    )
    ticket = _get_ticket_or_none(parsed_id)
    return jsonify(_serialize_row(ticket))


@app.route("/tickets/<ticket_id>/messages", methods=["GET"])
def list_messages(ticket_id: str):
    """Return all messages for a ticket, oldest first."""
    ensure_tables()
    parsed_id = _parse_ticket_id(ticket_id)
    if parsed_id is None:
        return _error(
            "Invalid ticket id. Use a numeric ticket_id from the tickets list."
        )

    if not _get_ticket_or_none(parsed_id):
        return _error(f"Ticket #{parsed_id} was not found.", 404)

    rows = lakebase.run_query(
        f"""
        SELECT message_id, ticket_id, message_text, author, created_at
        FROM {MESSAGES_TABLE}
        WHERE ticket_id = %s
        ORDER BY created_at ASC
        """,
        (parsed_id,),
    )
    return jsonify([_serialize_row(r) for r in rows])


@app.route("/tickets/<ticket_id>/messages", methods=["POST"])
def add_message(ticket_id: str):
    """Add a message to an existing ticket."""
    ensure_tables()
    parsed_id = _parse_ticket_id(ticket_id)
    if parsed_id is None:
        return _error(
            "Invalid ticket id. Use a numeric ticket_id from the tickets list."
        )

    if not _get_ticket_or_none(parsed_id):
        return _error(f"Ticket #{parsed_id} was not found.", 404)

    data = request.get_json(silent=True)
    if data is None:
        return _error('Request body must be JSON, e.g. {"message_text": "Hello"}.')

    message_text, err = _validate_message_text(data.get("message_text"))
    if err:
        return _error(err, fields={"message_text": err})

    author = _current_user_email()
    rows = lakebase.run_write_returning(
        f"""
        INSERT INTO {MESSAGES_TABLE} (ticket_id, message_text, author, created_at)
        VALUES (%s, %s, %s, now())
        RETURNING message_id, ticket_id, message_text, author, created_at
        """,
        (parsed_id, message_text, author),
    )
    return jsonify(_serialize_row(rows[0])), 201


