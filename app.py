"""
Databricks App:
- Serves a small Flask API + UI for support tickets
- Reads/writes to Lakebase (Databricks-managed Postgres) via lakebase.py

Run locally:
    python app.py
Deploy as a Databricks App using app.yaml.
"""

import logging
import os

from databricks.sdk import WorkspaceClient
from flask import Flask, jsonify, render_template, request

import lakebase

logging.basicConfig(level=logging.INFO)
logger = logging.getLogger("tickets-app")

app = Flask(__name__)
_w = WorkspaceClient()

TICKETS_TABLE = os.environ.get("TICKETS_TABLE_NAME", "tickets")
MESSAGES_TABLE = os.environ.get("TICKET_MESSAGES_TABLE_NAME", "ticket_messages")

VALID_STATUSES = ("open", "in_progress", "solved")
VALID_PRIORITIES = ("low", "medium", "high", "urgent")
VALID_CATEGORIES = ("general", "billing", "technical", "account", "other")

TITLE_MIN_LEN = 3
TITLE_MAX_LEN = 200
MESSAGE_MIN_LEN = 1
MESSAGE_MAX_LEN = 5000

TICKET_COLUMNS = (
    "ticket_id, title, status, priority, category, created_by, created_at"
)


def ensure_tables():
    """Create tickets and ticket_messages tables in Lakebase if they don't exist yet.

    IDs are BIGINT to match existing Lakebase tables. ticket_messages.ticket_id is
    not declared as a DB foreign key because the existing tickets table may not
    have a PRIMARY KEY/UNIQUE on ticket_id (Postgres requires that for FKs).
    The API still enforces that messages reference a real ticket.
    """
    lakebase.run_write(
        f"""
        CREATE TABLE IF NOT EXISTS {TICKETS_TABLE} (
            ticket_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            title TEXT NOT NULL,
            status TEXT NOT NULL DEFAULT 'open',
            priority TEXT NOT NULL DEFAULT 'medium',
            category TEXT NOT NULL DEFAULT 'general',
            created_by TEXT NOT NULL,
            created_at TIMESTAMPTZ NOT NULL DEFAULT now()
        )
        """
    )
    # Migrate existing tickets tables that predate priority/category.
    for column, default in (("priority", "medium"), ("category", "general")):
        try:
            lakebase.run_write(
                f"""
                ALTER TABLE {TICKETS_TABLE}
                ADD COLUMN IF NOT EXISTS {column} TEXT NOT NULL DEFAULT '{default}'
                """
            )
        except Exception:
            logger.warning(
                "Could not add column %s on %s", column, TICKETS_TABLE, exc_info=True
            )

    try:
        lakebase.run_write(
            f"""
            DO $$
            BEGIN
                IF NOT EXISTS (
                    SELECT 1
                    FROM pg_constraint c
                    JOIN pg_class t ON c.conrelid = t.oid
                    JOIN unnest(c.conkey) AS col(attnum) ON true
                    JOIN pg_attribute a
                      ON a.attrelid = t.oid AND a.attnum = col.attnum
                    WHERE t.relname = '{TICKETS_TABLE}'
                      AND c.contype IN ('p', 'u')
                      AND a.attname = 'ticket_id'
                ) THEN
                    ALTER TABLE {TICKETS_TABLE}
                        ADD CONSTRAINT tickets_ticket_id_key UNIQUE (ticket_id);
                END IF;
            END $$;
            """
        )
    except Exception:
        logger.warning(
            "Could not ensure UNIQUE(ticket_id) on %s; continuing without DB FK",
            TICKETS_TABLE,
            exc_info=True,
        )

    try:
        lakebase.run_write(
            f"""
            CREATE TABLE IF NOT EXISTS {MESSAGES_TABLE} (
                message_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                ticket_id BIGINT NOT NULL REFERENCES {TICKETS_TABLE}(ticket_id),
                message_text TEXT NOT NULL,
                author TEXT NOT NULL,
                created_at TIMESTAMPTZ NOT NULL DEFAULT now()
            )
            """
        )
    except Exception:
        logger.warning(
            "Creating %s without foreign key (tickets.ticket_id is not unique)",
            MESSAGES_TABLE,
            exc_info=True,
        )
        lakebase.run_write(
            f"""
            CREATE TABLE IF NOT EXISTS {MESSAGES_TABLE} (
                message_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                ticket_id BIGINT NOT NULL,
                message_text TEXT NOT NULL,
                author TEXT NOT NULL,
                created_at TIMESTAMPTZ NOT NULL DEFAULT now()
            )
            """
        )

    lakebase.run_write(
        f"""
        CREATE INDEX IF NOT EXISTS {MESSAGES_TABLE}_ticket_id_idx
        ON {MESSAGES_TABLE} (ticket_id)
        """
    )


def _parse_ticket_id(ticket_id: str) -> int | None:
    try:
        return int(ticket_id)
    except (TypeError, ValueError):
        return None


def _current_user_email() -> str:
    """
    Resolve the current user's email.

    Databricks Apps inject the logged-in user's identity via the
    X-Forwarded-Email header on every request. Fall back to the Databricks
    SDK's current_user API for local development where that header isn't set.
    """
    header_email = request.headers.get("X-Forwarded-Email")
    if header_email:
        return header_email
    return _w.current_user.me().user_name


def _serialize_row(row: dict) -> dict:
    """Convert DB row values (e.g. datetime) into JSON-safe types."""
    out = dict(row)
    for key, value in out.items():
        if hasattr(value, "isoformat"):
            out[key] = value.isoformat()
    return out


def _error(message: str, status: int = 400, *, fields: dict | None = None):
    payload = {"error": message}
    if fields:
        payload["fields"] = fields
    return jsonify(payload), status


def _validate_title(title: object) -> tuple[str | None, str | None]:
    if not isinstance(title, str):
        return None, "Title is required and must be text."
    cleaned = title.strip()
    if not cleaned:
        return None, "Title is required."
    if len(cleaned) < TITLE_MIN_LEN:
        return None, f"Title must be at least {TITLE_MIN_LEN} characters."
    if len(cleaned) > TITLE_MAX_LEN:
        return None, f"Title must be at most {TITLE_MAX_LEN} characters."
    return cleaned, None


def _validate_choice(
    value: object,
    *,
    field: str,
    allowed: tuple[str, ...],
    default: str | None = None,
    required: bool = False,
) -> tuple[str | None, str | None]:
    if value is None or (isinstance(value, str) and not value.strip()):
        if required:
            return None, f"{field} is required. Choose one of: {', '.join(allowed)}."
        return default, None
    if not isinstance(value, str):
        return None, f"{field} must be text. Allowed values: {', '.join(allowed)}."
    cleaned = value.strip().lower()
    if cleaned not in allowed:
        return None, f"Invalid {field} '{value}'. Allowed values: {', '.join(allowed)}."
    return cleaned, None


def _validate_message_text(message_text: object) -> tuple[str | None, str | None]:
    if not isinstance(message_text, str):
        return None, "Message text is required and must be text."
    cleaned = message_text.strip()
    if len(cleaned) < MESSAGE_MIN_LEN:
        return None, "Message text is required."
    if len(cleaned) > MESSAGE_MAX_LEN:
        return None, f"Message text must be at most {MESSAGE_MAX_LEN} characters."
    return cleaned, None


def _get_ticket_or_none(ticket_id: int) -> dict | None:
    rows = lakebase.run_query(
        f"""
        SELECT {TICKET_COLUMNS}
        FROM {TICKETS_TABLE}
        WHERE ticket_id = %s
        """,
        (ticket_id,),
    )
    return rows[0] if rows else None


